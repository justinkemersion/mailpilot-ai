-- Flux bootstraps these roles for v1_dedicated projects. Keep grants explicit
-- so a dump/restore or local reset leaves PostgREST with the expected access.
grant usage on schema api to anon, authenticated, service_role;
grant select, insert, update, delete on all tables in schema api to anon, authenticated, service_role;
grant usage, select on all sequences in schema api to anon, authenticated, service_role;
grant execute on all functions in schema api to anon, authenticated, service_role;

alter default privileges in schema api
  grant select, insert, update, delete on tables to anon, authenticated, service_role;
alter default privileges in schema api
  grant usage, select on sequences to anon, authenticated, service_role;
